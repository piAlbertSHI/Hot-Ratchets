function report=verify_sun_band_shape_factor_contract()
%VERIFY_SUN_BAND_SHAPE_FACTOR_CONTRACT
% Short numerical check of the source Eq.(28)--(30) shape-factor kernel.
root=fileparts(fileparts(mfilename('fullpath'))); addpath(fullfile(root, 'matlab'));
[H02,m02]=sma.candidate_sun_band_shape_factor_1d(.2,.30);
[H1,m1]=sma.candidate_sun_band_shape_factor_1d(1,.30);
[H2,m2]=sma.candidate_sun_band_shape_factor_1d(2,.30);
[H5,m5]=sma.candidate_sun_band_shape_factor_1d(5,.30);
assert(all(isfinite([H02 H1 H2 H5])) && all([H02 H1 H2 H5]>0), ...
    'Nonfinite/nonpositive source shape factor.');
assert(H02>H1 && H1>H2 && H2>H5, ...
    'Expected decreasing H(l/a,nu) branch was not reproduced.');
Wscale=[.2*H02,1*H1,2*H2,5*H5];
assert(all(isfinite(Wscale)) && Wscale(2)>Wscale(1) && Wscale(2)>Wscale(3), ...
    'Eq.(31) length-energy scale does not show the source peak branch.');

bad_lambda=false; try, sma.candidate_sun_band_shape_factor_1d(0,.3); catch, bad_lambda=true; end
bad_nu=false; try, sma.candidate_sun_band_shape_factor_1d(1,.6); catch, bad_nu=true; end
assert(bad_lambda && bad_nu,'Invalid shape-factor domain was accepted.');
checks=struct('positive_finite',true,'H_decreasing',true,'length_energy_peak_branch',true, ...
    'invalid_lambda_rejected',bad_lambda,'invalid_nu_rejected',bad_nu, ...
    'validation_only',m1.validation_only,'source_authority_false',~m1.source_authoritative, ...
    'production_disconnected',~m1.production_connected);
names=fieldnames(checks); values=cellfun(@(n)logical(checks.(n)),names);
report=struct('schema_id','SUN_BAND_SHAPE_FACTOR_CONTRACT_V1','all_pass',all(values), ...
    'checks',checks,'shape_factors',struct('lambda_0_2',H02,'lambda_1',H1, ...
    'lambda_2',H2,'lambda_5',H5),'quadrature',struct('lambda_0_2',m02, ...
    'lambda_1',m1,'lambda_2',m2,'lambda_5',m5),'production_connected',false, ...
    'source_authoritative',false,'state_modified',false,'observation_accessed',false, ...
    'experimental_backfill',false,'experimental_acceptance',false);
assert(report.all_pass,'SUN band shape-factor contract failed.');
fprintf('PASS_SUN_BAND_SHAPE_FACTOR_CONTRACT\n');
end
