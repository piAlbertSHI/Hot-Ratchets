function report=verify_unified_state_contract_1d()
%VERIFY_UNIFIED_STATE_CONTRACT_1D Contract-only unified-state regression.

root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root, 'matlab'));

source_state=valid_state('source_cohort','zhang_source_xi_Mr');
source_receipt=sma.validate_unified_state_contract_1d(source_state);
assert(source_receipt.cohort_path_ledger_eligible && ...
    strcmp(source_receipt.residual_M_authority,'zhang_source_xi_Mr'));

legacy_state=valid_state('legacy_bulk','reduced_legacy_xi_res');
legacy_receipt=sma.validate_unified_state_contract_1d(legacy_state);
assert(~legacy_receipt.cohort_path_ledger_eligible && ...
    strcmp(legacy_receipt.residual_M_authority,'reduced_legacy_xi_res'));

cases={ ...
    'phase_closure',@(s)set_nested(s,'phase','xi_A',0.61), ...
    'relative_R',@(s)set_nested(s,'phase','relative_R_within_AR',0.1), ...
    'strain_closure',@(s)set_nested(s,'strain','eps_total',0.123), ...
    'residual_authority',@(s)set_nested(s,'residual_martensite', ...
        'source_field_name','xi_res'), ...
    'lossy_cohort',@(s)set_nested(s,'plastic_ledger','lossless_lineage',false), ...
    'missing_identity',@(s)rmfield(s,'identity')};
rejections=struct();
for k=1:2:numel(cases)
    name=cases{k}; mutate=cases{k+1};
    rejections.(name)=must_reject(mutate(source_state));
end
assert(all(structfun(@(v)v,rejections)), ...
    'Unified-state negative contracts did not all reject.');

fully_martensitic=source_state;
fully_martensitic.phase=struct('xi_A',0.0,'xi_R',0.0,'xi_M',1.0, ...
    'relative_R_within_AR',0.0,'relative_R_defined',false);
fully_martensitic.residual_martensite.value=0.02;
fully_martensitic.reversal_memory.xi_M_forward_anchor=1.0;
full_M_receipt=sma.validate_unified_state_contract_1d(fully_martensitic);
assert(full_M_receipt.relative_R_residual==0.0);

report=struct( ...
    'status','PASS_UNIFIED_STATE_CONTRACT_V1', ...
    'source_state',source_receipt, ...
    'legacy_state',legacy_receipt, ...
    'fully_martensitic_state',full_M_receipt, ...
    'negative_cases',rejections, ...
    'synthetic_contract_only',true, ...
    'production_forward_connected',false, ...
    'experimental_data_read',false, ...
    'experimental_acceptance',false);
fprintf('%s\n',report.status);
end

function state=valid_state(plastic_representation,residual_authority)
state=struct();
state.schema='unified_state_1d_v1';
state.identity=struct( ...
    'material_card_id','synthetic_contract_card', ...
    'model_variant_id','contract_only', ...
    'state_id','synthetic_step_1');
state.phase=struct('xi_A',0.60,'xi_R',0.15,'xi_M',0.25, ...
    'relative_R_within_AR',0.20,'relative_R_defined',true);
state.strain=struct( ...
    'eps_elastic',0.0030,'eps_thermal',0.0001,'eps_R',0.0005, ...
    'eps_MT',0.0100,'eps_TRIP',0.0002,'eps_ARP',0.0003, ...
    'eps_total',0.0141);
if strcmp(residual_authority,'zhang_source_xi_Mr')
    source_field='zhang_xi_Mr';
else
    source_field='xi_res';
end
state.residual_martensite=struct( ...
    'authority',residual_authority,'source_field_name',source_field, ...
    'value',0.02);
state.reversal_memory=struct( ...
    'xi_M_forward_anchor',0.30,'eps_MT_forward_anchor',0.0120);
if strcmp(plastic_representation,'source_cohort')
    lineage_reference='synthetic_cohort_receipt_sha256';
    lossless_lineage=true;
else
    lineage_reference='';
    lossless_lineage=false;
end
state.plastic_ledger=struct( ...
    'representation',plastic_representation, ...
    'lineage_reference',lineage_reference, ...
    'lossless_lineage',lossless_lineage);
end

function state=set_nested(state,parent,name,value)
state.(parent).(name)=value;
end

function rejected=must_reject(state)
rejected=false;
try
    sma.validate_unified_state_contract_1d(state);
catch exception
    rejected=startsWith(exception.identifier,'sma:unified_state_contract:');
end
end
