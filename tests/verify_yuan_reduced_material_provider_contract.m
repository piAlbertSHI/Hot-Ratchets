function report = verify_yuan_reduced_material_provider_contract()
%VERIFY_YUAN_REDUCED_MATERIAL_PROVIDER_CONTRACT
% Regression for isolated legacy-reduced Cu-Al-Mn material/event providers.
root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root, 'matlab'));
p = sma.params('cualmn_annealed');
old = sma.initial_state_1d(p);

control = struct('mode','engineering_strain_rate', ...
    'signed_rate_1_per_s',0.15);
[trial,step] = sma.candidate_yuan_reduced_material_step_1d( ...
    p,old,control,p.Tamb,0.01);
engineering_increment = exp(trial.eps)-1-(exp(old.eps)-1);
assert(abs(engineering_increment-0.0015)<=1e-10, ...
    'Engineering strain-rate mapping is inconsistent.');
assert(step.accepted && ~step.state_commit && ~step.production_connected && ...
    ~step.source_authoritative_complete && ~step.experimental_acceptance, ...
    'Reduced candidate was promoted beyond its provenance.');
assert(step.reaction_extent_normalized==step.martensite_fraction && ...
    strcmp(step.inventory_semantics,'normalized_reaction_not_measured_phase') && ...
    ~step.martensite_fraction_is_observation, ...
    'Reduced Yuan extent semantics were not carried explicitly.');
assert(abs(step.control_residual)<=1e-9 && ...
    abs(step.thermal_balance_defect_Jkg)<=1e-8, ...
    'Reduced material step failed its numerical balances.');

[event_state,event] = sma.candidate_yuan_strain_rate_event_step_1d( ...
    p,old,0.15,20,p.Tamb,0.01,1e-6);
assert(event.event_crossed && event.event_reached && ...
    abs(event.event_residual_MPa)<=1e-6 && ...
    event.accepted_dt_s>0 && event.accepted_dt_s<0.01, ...
    'Loading stress event was not located inside the strain-rate step.');
assert(event.endpoint_assignment_used==false && ...
    abs(event_state.sigma-20)<=1e-6, ...
    'Stress event used assignment or missed the constitutive root.');

hold = struct('mode','stress_hold','target_stress_MPa',event_state.sigma);
[held,hold_receipt] = sma.candidate_yuan_reduced_material_step_1d( ...
    p,event_state,hold,p.Tamb,0.01);
assert(abs(held.sigma-event_state.sigma)<=1e-8 && ...
    abs(hold_receipt.control_residual)<=1e-8, ...
    'Stress-hold provider failed its control residual.');

non_yuan_rejected = false;
try
    pn = sma.params('niti_zhang2022');
    sma.candidate_yuan_reduced_material_step_1d( ...
        pn,sma.initial_state_1d(pn),control,pn.Tamb,0.01);
catch ME
    non_yuan_rejected = strcmp(ME.identifier, ...
        'sma:candidate_yuan_reduced_material_step_1d:MaterialRole');
end
assert(non_yuan_rejected,'Non-Yuan material did not fail closed.');

report = struct('all_pass',true, ...
    'status','PASS_LEGACY_REDUCED_PROVIDER_CONTRACT', ...
    'engineering_strain_increment',engineering_increment, ...
    'event_stress_MPa',event_state.sigma, ...
    'event_residual_MPa',event.event_residual_MPa, ...
    'event_elapsed_s',event.accepted_dt_s, ...
    'step_constitutive_residual',step.constitutive_residual, ...
    'step_thermal_defect_Jkg',step.thermal_balance_defect_Jkg, ...
    'material_model_role',step.material_model_role, ...
    'production_connected',false,'source_authoritative_complete',false, ...
    'observation_accessed',false,'experimental_acceptance',false, ...
    'full_phase_root',false,'full_thermal_root',false);
disp(report);
end
