function report=verify_mixed_mt_properties_contract()
%VERIFY_MIXED_MT_PROPERTIES_CONTRACT Zhang Eqs. (6)/(37-b) endpoints.

root=fileparts(fileparts(mfilename('fullpath'))); addpath(fullfile(root, 'matlab'));
p=sma.params('niti_zhang2022');
g_A_M=p.Hmax_i;
[g_A,eta_A,r_A,g_R_M]=sma.mixed_mt_properties(p,0.2,0.0,g_A_M);
[g_R,eta_R,r_R]=sma.mixed_mt_properties(p,0.2,0.8,g_A_M);
xi_R_mid=0.35*(1.0-0.2);
[g_mid,eta_mid,r_mid]=sma.mixed_mt_properties( ...
    p,0.2,xi_R_mid,g_A_M);
expected_g_mid=(1.0-r_mid)*g_A_M+r_mid*g_R_M;
expected_eta_mid=p.rho_delta_s-r_mid*p.R_entropy;
errors=[abs(g_A-g_A_M),abs(eta_A-p.rho_delta_s),abs(r_A), ...
    abs(g_R-g_R_M),abs(eta_R-(p.rho_delta_s-p.R_entropy)), ...
    abs(r_R-1.0),abs(g_mid-expected_g_mid), ...
    abs(eta_mid-expected_eta_mid),abs(r_mid-0.35), ...
    abs((p.R_H+g_R_M)-g_A_M)];
assert(max(errors)<5.0e-14, ...
    'Zhang mixed-MT property contract is not satisfied.');
report=struct('passed',true,'max_error',max(errors), ...
    'g_A_M',g_A_M,'g_R_M',g_R_M, ...
    'delta_eta_A_R',p.R_entropy, ...
    'delta_eta_A_M',p.rho_delta_s, ...
    'generated_at',datetime('now','TimeZone','Asia/Singapore'));
end
