function report=verify_sun_band_energy_gradient_contract()
%VERIFY_SUN_BAND_ENERGY_GRADIENT_CONTRACT
% Short check of dW/dl derived from the source band-energy kernel.
root=fileparts(fileparts(mfilename('fullpath'))); addpath(fullfile(root, 'matlab'));
[d05,m05]=sma.candidate_sun_band_energy_gradient_1d(1e-4,60000,.30,.02,.5);
[d2,m2]=sma.candidate_sun_band_energy_gradient_1d(1e-4,60000,.30,.02,2);
assert(isfinite(d05) && isfinite(d2) && d05>0 && d2<0, ...
    'Source band-energy gradient did not show the expected sign change.');
% Independent local central difference of lambda*H checks the chain rule.
[Hm,~]=sma.candidate_sun_band_shape_factor_1d(.5-5e-4,.30);
[Hp,~]=sma.candidate_sun_band_shape_factor_1d(.5+5e-4,.30);
scale=pi*(1e-4)^2*60000*.02^2/(1-.30);
d_fd=scale*((Hp*(.5+5e-4)-Hm*(.5-5e-4))/(1e-3));
assert(abs(d_fd-d05)<=5e-6*max(abs(d05),eps), ...
    'dW/dl chain rule disagrees with independent central difference.');
checks=struct('finite',true,'positive_prepeak',d05>0,'negative_postpeak',d2<0, ...
    'independent_chain_rule',true,'validation_only',m05.validation_only, ...
    'source_authority_false',~m05.source_authoritative, ...
    'production_disconnected',~m05.production_connected);
names=fieldnames(checks); values=cellfun(@(n)logical(checks.(n)),names);
report=struct('schema_id','SUN_BAND_ENERGY_GRADIENT_CONTRACT_V1','all_pass',all(values), ...
    'checks',checks,'dWdl_MPa_m2',struct('lambda_0_5',d05,'lambda_2',d2), ...
    'metadata',struct('lambda_0_5',m05,'lambda_2',m2), ...
    'production_connected',false,'source_authoritative',false, ...
    'state_modified',false,'observation_accessed',false, ...
    'experimental_backfill',false,'experimental_acceptance',false);
assert(report.all_pass,'SUN band-energy gradient contract failed.');
fprintf('PASS_SUN_BAND_ENERGY_GRADIENT_CONTRACT\n');
end
