function x = state_vector_1d(s)
%SMA.STATE_VECTOR_1D Pack the committed state for Simulink.

if isfield(s,'Y_population_activity') && ...
        any(abs(s.Y_population_activity(:))>100*eps)
    error('sma:state_vector_1d:LossyPopulationState', ...
        ['The legacy 15-value state cannot serialize nonzero threshold-' ...
         'population history. Use sma.state_vector_1d_v2.']);
end
zhang_names={'zhang_xi_Mr','zhang_rho_M','zhang_rho_AR','zhang_D_M', ...
    'zhang_D_AR','zhang_DeltaEtaP','zhang_Omega','zhang_Yp', ...
    'zhang_Lambda_M'};
for k=1:numel(zhang_names)
    if isfield(s,zhang_names{k}) && abs(s.(zhang_names{k}))>100*eps
        error('sma:state_vector_1d:LossyZhangState', ...
            ['The legacy 15-value state cannot serialize nonzero Zhang ' ...
             'history. Use sma.pack_state_1d with the active parameters.']);
    end
end
if isfield(s,'xi_R') && abs(s.xi_R)>100*eps
    error('sma:state_vector_1d:LossyRPhaseState', ...
        ['The legacy 15-value state cannot serialize a nonzero R-phase ' ...
         'fraction. Use sma.pack_state_1d with the active parameters.']);
end

x = [s.T; s.xi; s.eps_tr; s.eps_tp; s.zeta_d; s.beta; ...
    s.sigma; s.eps; s.branch; s.direction; s.xi_r; s.eps_tr_r; ...
    s.eps_arp; s.xi_res; s.zeta_p];
end
