function [gradient,audit]=candidate_population_gradient_map_1d( ...
    xi_old,xi_new,population_count,spatial_count,population_weights, ...
    kappa_MPa_length2,Dxx)
%SMA.CANDIDATE_POPULATION_GRADIENT_MAP_1D
% Map a q-major population state to the population-averaged spatial
% gradient force. The flattened order is [j=1..Nx] inside each q.
np=round(population_count); nx=round(spatial_count);
pi=population_weights(:); xi_old=xi_old(:); xi_new=xi_new(:);
assert(np>=1 && nx>=1 && numel(pi)==np && all(pi>0) && ...
    abs(sum(pi)-1)<=1e-12,'Population weights are inadmissible.');
assert(numel(xi_old)==nx*np && numel(xi_new)==nx*np && ...
    all(isfinite(xi_old)) && all(isfinite(xi_new)), ...
    'Population state width or values are inadmissible.');
assert(isequal(size(Dxx),[nx,nx]) && all(isfinite(Dxx(:))) && ...
    isfinite(kappa_MPa_length2), ...
    'Spatial gradient operator or coefficient is inadmissible.');

% MATLAB column-major flattening of an Nx-by-Np state is q-major: the
% spatial index varies fastest inside each population. Reconstruct that
% exact layout before averaging over population columns.
old_space_population=reshape(xi_old,nx,np);
new_space_population=reshape(xi_new,nx,np);
old_spatial_mean=old_space_population*pi;
new_spatial_mean=new_space_population*pi;
midpoint_spatial_mean=0.5*(old_spatial_mean+new_spatial_mean);
gradient_space=kappa_MPa_length2*Dxx*midpoint_spatial_mean;

% Every population at a spatial location consumes the same coarse-grained
% spatial gradient force. Repeating the Nx-vector Np times preserves the
% q-major flattened order expected by the phase kernel.
gradient=repmat(gradient_space,np,1);
audit=struct('layout','q-major_spatial-fast', ...
    'old_spatial_mean',old_spatial_mean, ...
    'new_spatial_mean',new_spatial_mean, ...
    'midpoint_spatial_mean',midpoint_spatial_mean, ...
    'gradient_space_MPa',gradient_space, ...
    'population_count',np,'spatial_count',nx, ...
    'observation_accessed',false,'production_connected',false);
end
