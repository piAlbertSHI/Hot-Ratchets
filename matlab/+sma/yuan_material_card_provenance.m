function receipt = yuan_material_card_provenance(case_name,runtime_card)
%SMA.YUAN_MATERIAL_CARD_PROVENANCE Audit roles in legacy Cu-Al-Mn cards.
%
% The Yuan paper is an experimental source, not a constitutive parameter
% table.  This receipt separates literal/derived source facts from the
% project's legacy reduced/calibrated closures.  It does not modify P and
% it never promotes a card to source-authoritative status.

if nargin<2 || isempty(runtime_card)
    p = sma.params(case_name);
else
    assert(isstruct(runtime_card) && isfield(runtime_card,'case_id'), ...
        'sma:yuan_material_card_provenance:RuntimeCard', ...
        'Runtime card must be a parameter struct with case_id.');
    p = runtime_card;
end
assert(any(p.case_id==[2,3,4]), ...
    'sma:yuan_material_card_provenance:MaterialRole', ...
    'Yuan material provenance is defined only for Cu-Al-Mn cases 2--4.');
authority = sma.protocol_authority(case_name);

source = source_values(p.case_id);
direct_names = {'Ms','Mf','As','Af','CM','rho'};
direct_error = struct();
direct_match = true;
for k=1:numel(direct_names)
    name = direct_names{k};
    err = p.(name)-source.(name);
    direct_error.(name) = err;
    direct_match = direct_match && abs(err)<=1e-12;
end

entropy_closure = -p.CM*p.Hmax_i;
entropy_closure_error = p.rho_delta_s-entropy_closure;
adiabatic_scale_K = p.latent/p.cp;
reported_temperature_rise_K = source.reported_temperature_rise_K;
temperature_scale_coincidence_K = ...
    adiabatic_scale_K-reported_temperature_rise_K;

roles = struct( ...
    'Ms','source_direct_method_scoped_damping_not_unique_DSC', ...
    'Mf','source_direct_method_scoped_damping_not_unique_DSC', ...
    'As','source_direct_method_scoped_damping_not_unique_DSC', ...
    'Af','source_direct_method_scoped_damping_not_unique_DSC', ...
    'CM','source_direct_Clausius_Clapeyron_slope_contextual', ...
    'CA','legacy_equal_to_CM_not_source_direct', ...
    'rho','source_literal_density', ...
    'cp','source_literal_expected_410_but_card_may_be_legacy', ...
    'EA','legacy_reduced_or_curve_derived_not_literal_table', ...
    'EM','legacy_reduced_or_curve_derived_not_literal_table', ...
    'Hmax_i','legacy_observation_aligned_not_literal_constitutive_parameter', ...
    'Hmax_f','legacy_cycle_envelope_calibration', ...
    'rho_delta_s','derived_CC_closure_from_CM_times_Hmax', ...
    'latent','stress_induced_reversible_heat_branch_not_DSC_exothermic_enthalpy', ...
    'latent_f','legacy_cycle_envelope_calibration', ...
    'lambda_H','legacy_cycle_calibration', ...
    'lambda_latent','legacy_cycle_calibration', ...
    'zeta_H0','legacy_cycle_calibration', ...
    'zeta_latent0','legacy_cycle_calibration', ...
    'heat_loss_rate','legacy_reduced_heat_transfer_closure');

receipt = struct( ...
    'schema_id','yuan_material_card_provenance_v1', ...
    'case_name',char(case_name),'case_id',p.case_id, ...
    'material_card_id',material_card_id(p.case_id), ...
    'protocol_card_id',authority.protocol_card_id, ...
    'material_model_role','legacy_reduced_candidate', ...
    'parameter_provenance_status','mixed_source_derived_and_legacy', ...
    'source_authoritative_complete',false, ...
    'experimental_acceptance_allowed',false, ...
    'observation_accessed',false, ...
    'source_cp_J_kgK',source.cp, ...
    'card_cp_J_kgK',p.cp, ...
    'source_cp_mismatch',abs(p.cp-source.cp)>1e-12, ...
    'source_exothermic_enthalpy_Jkg',source.exothermic_enthalpy_Jkg, ...
    'card_latent_Jkg',p.latent, ...
    'source_enthalpy_mismatch', ...
        abs(p.latent-source.exothermic_enthalpy_Jkg)>1e-12, ...
    'source_DSC_enthalpy_is_not_required_to_equal_stress_induced_reversible_heat',true, ...
    'main_text_delta_s_sigma_J_kgK',source.main_text_delta_s_sigma_J_kgK, ...
    'supplement_curve_delta_s_sigma_J_kgK', ...
        source.supplement_curve_delta_s_sigma_J_kgK, ...
    'main_text_reversible_heat_Jkg', ...
        source.test_temperature_K*source.main_text_delta_s_sigma_J_kgK, ...
    'supplement_curve_reversible_heat_Jkg', ...
        source.test_temperature_K*source.supplement_curve_delta_s_sigma_J_kgK, ...
    'main_text_eq3_temperature_scale_K', ...
        source.test_temperature_K*source.main_text_delta_s_sigma_J_kgK/source.cp, ...
    'supplement_curve_eq3_temperature_scale_K', ...
        source.test_temperature_K*source.supplement_curve_delta_s_sigma_J_kgK/source.cp, ...
    'source_thermal_branch',thermal_source_branch(p,source), ...
    'source_thermal_branch_unique',false, ...
    'source_conflict_field','annealed_delta_s_print_vs_supplement_curve', ...
    'direct_source_fields_match',direct_match, ...
    'direct_source_field_error',direct_error, ...
    'entropy_CC_closure_MPaK',entropy_closure, ...
    'entropy_CC_closure_error_MPaK',entropy_closure_error, ...
    'card_adiabatic_scale_K',adiabatic_scale_K, ...
    'reported_temperature_rise_K',reported_temperature_rise_K, ...
    'temperature_scale_coincidence_K',temperature_scale_coincidence_K, ...
    'thermal_endpoint_coincidence', ...
        abs(temperature_scale_coincidence_K)<=0.02, ...
    'field_roles',roles, ...
    'production_connected',false);
end

function source = source_values(case_id)
source = struct('cp',410,'rho',7500,'exothermic_enthalpy_Jkg',4690, ...
    'test_temperature_K',303);
if case_id==2
    source.Ms=250; source.Mf=236; source.As=274; source.Af=291;
    source.CM=1.05; source.reported_temperature_rise_K=5.1;
    source.main_text_delta_s_sigma_J_kgK=5.0;
    source.supplement_curve_delta_s_sigma_J_kgK=6.9811303637848;
elseif case_id==3
    source.Ms=242; source.Mf=229; source.As=264; source.Af=279;
    source.CM=2.25; source.reported_temperature_rise_K=4.5;
    source.main_text_delta_s_sigma_J_kgK=10.3;
    source.supplement_curve_delta_s_sigma_J_kgK=10.400914346924942;
else
    source.Ms=242; source.Mf=229; source.As=264; source.Af=279;
    source.CM=2.25; source.reported_temperature_rise_K=3.0;
    source.main_text_delta_s_sigma_J_kgK=NaN;
    source.supplement_curve_delta_s_sigma_J_kgK=NaN;
end
end

function branch = thermal_source_branch(p,source)
tol = 1e-9;
main_heat = source.test_temperature_K*source.main_text_delta_s_sigma_J_kgK;
supplement_heat = ...
    source.test_temperature_K*source.supplement_curve_delta_s_sigma_J_kgK;
source_h_cc = source.rho*source.supplement_curve_delta_s_sigma_J_kgK/ ...
    (1.0e6*source.CM);
if abs(p.cp-source.cp)<=tol && abs(p.latent-supplement_heat)<=tol && ...
        abs(p.Hmax_i-source_h_cc)<=tol && ...
        abs(p.rho_delta_s+p.CM*p.Hmax_i)<=tol
    branch = 'supplement_s2_clausius';
elseif abs(p.cp-source.cp)<=tol && abs(p.latent-supplement_heat)<=tol
    branch = 'supplement_s2_curve';
elseif abs(p.cp-source.cp)<=tol && abs(p.latent-main_heat)<=tol
    branch = 'main_text_cp410';
elseif p.case_id==2 && abs(p.cp-297)<=tol && abs(p.latent-main_heat)<=tol
    branch = 'legacy_endpoint_aligned_cp297';
else
    branch = 'mixed_or_other';
end
end

function value = material_card_id(case_id)
cards = {'cualmn_annealed','cualmn_drawn130','cualmn_drawn80'};
value = cards{case_id-1};
end
