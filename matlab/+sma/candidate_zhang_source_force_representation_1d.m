function receipt=candidate_zhang_source_force_representation_1d( ...
    g,sigma,Btr,Omega,representation)
%SMA.CANDIDATE_ZHANG_SOURCE_FORCE_REPRESENTATION_1D Select one source printout.
% The main-text Eq. (36-b) uses g*(sigma+Btr).  The isolated 2026-10-07
% source-operator corrigendum resolves the uniaxial supplementary reduction
% as g*abs(sigma+Omega), with Omega remaining inside the absolute-value
% effective stress.  These are alternative source representations, not
% additive providers.  In particular, the rejected legacy interpretation
% g*sigma+Omega must never be used.

if nargin<5 || isempty(representation), representation='main_eq36b'; end
representation=lower(char(representation));
assert(all(isfinite([g,sigma,Btr,Omega])) && g>=0 && Omega>=0, ...
    'Source-force representation inputs must be finite and admissible.');
stress_term=g*sigma;
btr_term=g*Btr;
switch representation
    case 'main_eq36b'
        selected_history=btr_term;
        selected_formula='Zhang_main_Eq36b_g_sigma_plus_Btr';
        omega_selected=false;
    case 'supplement_s4a'
        selected_history=g*abs(sigma+Omega)-stress_term;
        selected_formula='Zhang_supplement_S4a_g_abs_sigma_plus_Omega';
        omega_selected=true;
    otherwise
        error('sma:candidate_zhang_source_force_representation_1d:UnknownRepresentation', ...
            'Unknown Zhang source-force representation: %s.',representation);
end
receipt=struct('representation',representation, ...
    'formula_id',selected_formula, ...
    'stress_transformation_MPa',stress_term, ...
    'main_Btr_contraction_MPa',btr_term, ...
    'supplement_Omega_MPa',Omega, ...
    'selected_history_force_MPa',selected_history, ...
    'mechanical_force_MPa',stress_term+selected_history, ...
    'supplement_minus_main_MPa',g*abs(sigma+Omega)-stress_term-btr_term, ...
    'omega_selected',omega_selected, ...
    'btr_selected',~omega_selected, ...
    'double_count_forbidden',true, ...
    'production_connected',false, ...
    'observation_accessed',false);
end
