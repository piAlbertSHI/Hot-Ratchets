function [trial, aux] = coupled_step_1d(p, state, mode, target, Tamb, dt)
%SMA.COUPLED_STEP_1D Staggered thermo-mechanical material-point step.
% mode 0: prescribed stress; mode 1: prescribed strain.

if nargin < 6 || isempty(dt)
    dt = p.default_dt;
end
heat_loss_rate = p.heat_loss_rate;
if is_hold_step(p,state,mode,target)
    heat_loss_rate = heat_loss_rate*p.hold_heat_multiplier;
end

if p.enable_iterated_thermomechanical_coupling
    [trial,aux] = iterated_coupling_with_cutback( ...
        p,state,mode,target,Tamb,dt,heat_loss_rate,0);
    return;
end

[first,first_aux] = mechanical_step(p,state,mode,target,state.T,dt);
[Tfirst,first_heat_loss] = thermal_update( ...
    p,state,first_aux,state.T,Tamb,dt,heat_loss_rate);
[corrected,corrected_aux] = mechanical_step( ...
    p,state,mode,target,Tfirst,dt);
if corrected.branch==first.branch
    trial = corrected;
    aux = corrected_aux;
    [Tnew,used_heat_loss] = thermal_update( ...
        p,state,aux,Tfirst,Tamb,dt,heat_loss_rate);
    iteration = 2;
else
    % Never commit heat generated by a rollback-only active-set probe.
    trial = first;
    aux = first_aux;
    Tnew = Tfirst;
    used_heat_loss = first_heat_loss;
    iteration = 1;
end
trial.T = Tnew;
aux.thermal_iterations = iteration;
% Report the same discrete heat-loss term actually used by thermal_update,
% not a posterior value evaluated at Tnew.
aux.heat_loss_specific_Jkg = used_heat_loss;
aux.heat_loss_rate_WkgK = heat_loss_rate;
aux.temperature_change = Tnew - state.T;
aux.thermal_converged = true;
aux.thermomechanical_temperature_residual_K = NaN;
aux.thermal_branch_switches = double(corrected.branch~=first.branch);
aux.thermal_cutbacks = 0;
aux.monolithic_thermal_solves = 0;
end

function [trial,aux] = iterated_coupling_with_cutback( ...
        p,state,mode,target,Tamb,dt,heat_loss_rate,depth)
try
    [trial,aux]=iterated_coupling( ...
        p,state,mode,target,Tamb,dt,heat_loss_rate);
    aux.thermal_cutbacks=0;
catch ME
    if ~strcmp(ME.identifier, ...
            'sma:coupled_step_1d:ThermomechanicalFixedPoint') || ...
            depth>=p.thermomechanical_coupling_max_cutbacks
        rethrow(ME);
    end
    try
        [trial,aux]=sma.monolithic_coupled_step_1d( ...
            p,state,mode,target,Tamb,dt,heat_loss_rate);
        return;
    catch monolithic_error
        if ~strcmp(monolithic_error.identifier, ...
                'sma:monolithic_coupled_step_1d:Newton')
            rethrow(monolithic_error);
        end
    end
    if mode==1
        committed_target=state.eps;
    else
        committed_target=state.sigma;
    end
    midpoint=0.5*(committed_target+target);
    [middle,first]=iterated_coupling_with_cutback( ...
        p,state,mode,midpoint,Tamb,0.5*dt,heat_loss_rate,depth+1);
    [trial,second]=iterated_coupling_with_cutback( ...
        p,middle,mode,target,Tamb,0.5*dt,heat_loss_rate,depth+1);
    aux=aggregate_cutback_aux(first,second,state,trial,heat_loss_rate);
end
end

function aux=aggregate_cutback_aux(first,second,state,trial,heat_loss_rate)
aux=second;
sum_fields={'strain_work_MPa','latent_specific_Jkg', ...
    'r_phase_latent_specific_Jkg','dissipation_specific_Jkg', ...
    'heat_loss_specific_Jkg','thermal_iterations', ...
    'thermal_branch_switches','monolithic_thermal_solves'};
for k=1:numel(sum_fields)
    field=sum_fields{k};
    if isfield(first,field) && isfield(second,field)
        aux.(field)=first.(field)+second.(field);
    end
end
aux.residual_norm=max(first.residual_norm,second.residual_norm);
aux.thermomechanical_temperature_residual_K=max( ...
    abs(first.thermomechanical_temperature_residual_K), ...
    abs(second.thermomechanical_temperature_residual_K));
aux.temperature_change=trial.T-state.T;
aux.heat_loss_rate_WkgK=heat_loss_rate;
aux.thermal_converged=first.thermal_converged && second.thermal_converged;
aux.thermal_cutbacks=first.thermal_cutbacks+second.thermal_cutbacks+1;
if isfield(first,'dissipation_nonnegative') && ...
        isfield(second,'dissipation_nonnegative')
    aux.dissipation_nonnegative=first.dissipation_nonnegative && ...
        second.dissipation_nonnegative;
end
end

function [trial,aux] = iterated_coupling( ...
        p,state,mode,target,Tamb,dt,heat_loss_rate)
% Solve the discrete heat balance and mechanical return map at one common
% temperature.  All probes start from STATE, so rejected active sets cannot
% mutate committed history or double-count latent heat.

temperature_probe=state.T;
previous_branch=NaN;
branch_switches=0;
converged=false;
temperature_residual=inf;
used_heat_loss=0.0;
for iteration=1:p.thermomechanical_coupling_max_iterations
    [candidate,candidate_aux]=mechanical_step( ...
        p,state,mode,target,temperature_probe,dt);
    [temperature_balance,used_heat_loss]=thermal_update( ...
        p,state,candidate_aux,temperature_probe,Tamb,dt,heat_loss_rate);
    temperature_residual=temperature_balance-temperature_probe;
    if isfinite(previous_branch) && candidate.branch~=previous_branch
        branch_switches=branch_switches+1;
    end
    previous_branch=candidate.branch;
    if abs(temperature_residual)<= ...
            p.thermomechanical_coupling_temperature_tol_K
        converged=true;
        trial=candidate;
        aux=candidate_aux;
        trial.T=temperature_balance;
        break;
    end
    temperature_probe=temperature_probe+ ...
        p.thermomechanical_coupling_relaxation*temperature_residual;
    temperature_probe=min(max(temperature_probe,p.min_temperature), ...
        p.max_temperature);
end
if ~converged
    error('sma:coupled_step_1d:ThermomechanicalFixedPoint', ...
        ['Thermo-mechanical fixed point did not converge in %d probes; ' ...
        'temperature residual is %.6g K.'],iteration,temperature_residual);
end
aux.thermal_iterations=iteration;
aux.heat_loss_specific_Jkg=used_heat_loss;
aux.heat_loss_rate_WkgK=heat_loss_rate;
aux.temperature_change=trial.T-state.T;
aux.thermal_converged=converged;
aux.thermomechanical_temperature_residual_K=temperature_residual;
aux.thermal_branch_switches=branch_switches;
aux.monolithic_thermal_solves=0;
end

function [trial,aux] = mechanical_step(p,state,mode,target,T,dt)
if mode==1
    [trial,aux] = sma.update_1d_strain(p,state,target,T,dt,false);
else
    [trial,aux] = sma.update_1d_stress(p,state,target,T,dt,false);
end
end

function [Tnew,heat_loss] = thermal_update( ...
        p,state,aux,Tprobe,Tamb,dt,heat_loss_rate)
heat_loss = heat_loss_rate*(Tprobe-Tamb)*dt;
Tnew = state.T+(aux.latent_specific_Jkg+ ...
    aux.dissipation_specific_Jkg-heat_loss)/p.cp;
Tnew = min(max(Tnew,p.min_temperature),p.max_temperature);
end

function held = is_hold_step(p,state,mode,target)
if mode==1
    held = abs(target-state.eps)<=p.hold_target_tol;
else
    held = abs(target-state.sigma)<=p.hold_target_tol;
end
end
