function [R, data] = residual_3d(p, state, tau, T, branch, reverse, x)
%SMA.RESIDUAL_3D Coupled tensor residual from the model report.
% x = [xi; h_tr(6); h_tp(6); zeta_d; beta(6)].

xi = x(1);
h_tr = sma.voigt_to_tensor(x(2:7));
h_tp = sma.voigt_to_tensor(x(8:13));
zeta_d = x(14);
beta = sma.voigt_to_tensor(x(15:20));
tau_eff = tau + beta;
[seq, dev_eff] = sma.equivalent_stress(tau_eff);
if branch < 0 && reverse.xi_r > p.numerics.xi_tol && ...
        norm(reverse.h_tr_r,'fro') > p.numerics.direction_tol
    N = reverse.h_tr_r / sqrt( ...
        (2.0/3.0) * sum(reverse.h_tr_r.^2,'all'));
elseif seq > p.numerics.direction_tol
    N = 1.5 * dev_eff / seq;
else
    N = state.N;
end

[Hcur, Hmax] = sma.hcur(p,seq,zeta_d);
ratio = min(max(Hcur / max(Hmax, eps), 0.0), 1.0);
[seq_R,~]=sma.equivalent_stress(tau);
[Hcur_mixed,delta_eta_AR_M,relative_R_for_MT,xi_R_for_MT] = ...
    sma.candidate_mixed_mt_properties( ...
    p,state,xi,seq_R,T,Hcur);
if branch > 0
    Lambda = Hcur_mixed * N;
else
    if reverse.xi_r > p.numerics.xi_tol
        Lambda = reverse.h_tr_r / reverse.xi_r;
    else
        Lambda = zeros(3);
    end
end

gp = p.Cp1 * p.Cp2 / (1.0 + p.Cp2 * max(zeta_d, 0.0));
if branch > 0
    Lambda_tp = ratio^2 * gp * N;
else
    if reverse.xi_r > p.numerics.xi_tol
        Lambda_tp = -ratio^2 * gp * reverse.h_tr_r / reverse.xi_r;
    else
        Lambda_tp = zeros(3);
    end
end

xi_d = ratio * xi;
% Back stress uses the unit J2 stress direction s_eff/seq=(2/3)N.
beta_target = (2.0/3.0) * p.sigma_b * ratio * ...
    (1.0 - exp(-p.lambda_beta * max(zeta_d, 0.0))) * N;
population_activity=sma.update_population_activity( ...
    p,state.Y_population_activity,state.xi,xi);
zhang_history=sma.candidate_zhang_history_3d( ...
    p,state,xi,h_tp,tau);
[pi_value, phi, force_terms] = sma.driving_force_3d( ...
    p,branch,tau,beta,T,xi,Lambda,Lambda_tp,zeta_d, ...
    reverse.xi_r,state.zeta_p,state.xi_res,population_activity, ...
    zhang_history.Yp,zhang_history.Omega,delta_eta_AR_M);
threshold = sma.transformation_resistance( ...
    p,branch,zeta_d,xi,reverse.xi_r,state.zeta_p,state.xi_res, ...
    population_activity,zhang_history.Yp);
delta_xi = xi - state.xi;
delta_xi_d = xi_d - state.xi_d;

strain_scale = max(p.Hmax_i, 1.0e-4);
trip_scale = max(p.Cp1, 1.0e-4);
beta_scale = max([p.sigma_b, p.reference_stress, 1.0]);
R = [
    phi / max(p.reference_stress, 1.0)
    sma.tensor_to_voigt(h_tr - state.h_tr - Lambda * delta_xi) / strain_scale
    sma.tensor_to_voigt(h_tp - state.h_tp - Lambda_tp * delta_xi) / trip_scale
    zeta_d - state.zeta_d - abs(delta_xi_d)
    sma.tensor_to_voigt(beta - beta_target) / beta_scale
    ];

data = struct( ...
    'phi', phi, ...
    'pi', pi_value, ...
    'force_terms', force_terms, ...
    'threshold', threshold, ...
    'seq', seq, ...
    'N', N, ...
    'Hcur', Hcur, ...
    'Hcur_mixed', Hcur_mixed, ...
    'Hmax', Hmax, ...
    'delta_eta_AR_M',delta_eta_AR_M, ...
    'relative_R_for_MT',relative_R_for_MT, ...
    'xi_R_for_MT',xi_R_for_MT, ...
    'ratio', ratio, ...
    'Lambda', Lambda, ...
    'Lambda_tp', Lambda_tp, ...
    'xi_d', xi_d, ...
    'Y_population_activity',population_activity, ...
    'zhang_history',zhang_history, ...
    'beta_target', beta_target);
end
