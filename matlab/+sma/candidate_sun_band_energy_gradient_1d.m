function [dWdl,meta]=candidate_sun_band_energy_gradient_1d(radius_m,E_MPa,nu,radial_eigenstrain,length_ratio)
%SMA.CANDIDATE_SUN_BAND_ENERGY_GRADIENT_1D
% Compute dW/dl from Sun/Zhong Eq.(31) through a source-shape-factor
% derivative.  This is a pure conditional kernel, not a kinetic evolution law.

assert(isnumeric(radius_m) && isscalar(radius_m) && isfinite(radius_m) && radius_m>0, ...
    'sma:sun_gradient:Domain','radius_m must be positive.');
assert(isnumeric(E_MPa) && isscalar(E_MPa) && isfinite(E_MPa) && E_MPa>0, ...
    'sma:sun_gradient:Domain','E_MPa must be positive.');
assert(isnumeric(nu) && isscalar(nu) && isfinite(nu) && nu>-1 && nu<.5, ...
    'sma:sun_gradient:Domain','nu must be in (-1,0.5).');
assert(isnumeric(radial_eigenstrain) && isscalar(radial_eigenstrain) && ...
    isfinite(radial_eigenstrain),'sma:sun_gradient:Domain', ...
    'radial_eigenstrain must be finite.');
assert(isnumeric(length_ratio) && isscalar(length_ratio) && isfinite(length_ratio) && ...
    length_ratio>0,'sma:sun_gradient:Domain','length_ratio must be positive.');

lambda=double(length_ratio); h=max(1e-4,1e-3*lambda);
if lambda-h<=0, h=lambda/2; end
[Hm,mm]=sma.candidate_sun_band_shape_factor_1d(lambda-h,nu);
[H0,m0]=sma.candidate_sun_band_shape_factor_1d(lambda,nu);
[Hp,mp]=sma.candidate_sun_band_shape_factor_1d(lambda+h,nu);
dH=(Hp-Hm)/(2*h);
scale=pi*double(radius_m)^2*double(E_MPa)*double(radial_eigenstrain)^2/(1-double(nu));
dWdl=scale*(H0+lambda*dH);
meta=struct('source_equations','SunZhong2000_Eq28_Eq31', ...
    'length_ratio',lambda,'difference_step',h,'H_minus',Hm,'H_zero',H0, ...
    'H_plus',Hp,'dH_dlambda',dH,'energy_scale_MPa_m2',scale, ...
    'shape_meta_minus',mm,'shape_meta_zero',m0,'shape_meta_plus',mp, ...
    'validation_only',true,'source_authoritative',false, ...
    'production_connected',false,'state_modified',false,'observation_accessed',false);
assert(isfinite(dWdl),'sma:sun_gradient:Numerics', ...
    'Sun band-energy gradient is nonfinite.');
end
