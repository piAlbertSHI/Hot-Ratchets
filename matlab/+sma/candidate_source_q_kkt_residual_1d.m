function [residual,receipt]=candidate_source_q_kkt_residual_1d( ...
    pi_MPa,Y_MPa,direction,q_trial,dt_s,r0,m,capacity,available)
%SMA.CANDIDATE_SOURCE_Q_KKT_RESIDUAL_1D Directional source-rate q/KKT map.
% All residuals are dimensionless q residuals, never added to dLambda.
% Physical state updates still use direction*dt*r0*q^m, including genuine
% floating-point underflow; q itself remains an independent trial variable.
assert(all(isfinite([pi_MPa,Y_MPa,direction,q_trial,dt_s,r0,m,capacity])) && ...
    Y_MPa>0 && abs(direction)==1 && q_trial>=0 && dt_s>0 && r0>0 && ...
    m>0 && capacity>=0 && isscalar(available), ...
    'sma:source_q:Input','Invalid source-q/KKT input.');
q_capacity=(capacity/(dt_s*r0))^(1/m);
q_demand=0;
if available && direction*pi_MPa>0
    q_demand=direction*pi_MPa/Y_MPa;
end
q_target=min(q_demand,q_capacity);
residual=q_trial-q_target;
mapped_increment=direction*dt_s*r0*q_trial^m;
receipt=struct('schema_id','SOURCE_Q_DIRECTIONAL_KKT_V1', ...
    'residual_kind','dimensionless_projected_q', ...
    'q_trial',q_trial,'q_demand',q_demand,'q_target',q_target, ...
    'q_capacity',q_capacity,'q_residual',residual, ...
    'direction',direction,'available',logical(available), ...
    'source_active',logical(available && direction*pi_MPa>0), ...
    'capacity_saturated',logical(q_demand>=q_capacity && q_capacity>0), ...
    'mapped_increment',mapped_increment, ...
    'mapping_underflow',logical(q_trial>0 && mapped_increment==0), ...
    'outward_force_margin_MPa',direction*pi_MPa-Y_MPa*q_capacity, ...
    'observation_accessed',false,'production_connected',false);
end
