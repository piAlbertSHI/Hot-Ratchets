function [strain,audit] = candidate_transformation_path_accommodation_1d( ...
    old_strain,sigma_MPa,path_increment,moduli_MPa,resistances_MPa)
%SMA.CANDIDATE_TRANSFORMATION_PATH_ACCOMMODATION_1D GSM path-flow kernel.
% The recoverable coordinates evolve per accumulated transformation path,
% not per clock time:
%   da_j/dLambda = (sigma-H_j*a_j)/R_j,
%   dLambda = abs(dlambda_R)+abs(dlambda_M).
% For a step-end stress held constant inside the local exact map,
%   a_{n+1}=sigma/H+(a_n-sigma/H)*exp(-H*dLambda/R).
% This isolated candidate has no protocol, stage, material-name, or
% observation access and is not connected to the production return map.

old_strain=double(old_strain(:));
moduli_MPa=double(moduli_MPa(:));
resistances_MPa=double(resistances_MPa(:));
assert(~isempty(old_strain) && numel(old_strain)==numel(moduli_MPa) && ...
    numel(old_strain)==numel(resistances_MPa), ...
    'sma:candidate_transformation_path_accommodation_1d:Width', ...
    'State, modulus, and path-resistance vectors must have equal width.');
assert(all(isfinite(old_strain)) && all(isfinite(moduli_MPa)) && ...
    all(isfinite(resistances_MPa)) && all(moduli_MPa>0) && ...
    all(resistances_MPa>0) && isfinite(sigma_MPa) && ...
    isfinite(path_increment) && path_increment>=0, ...
    'sma:candidate_transformation_path_accommodation_1d:Input', ...
    'Finite state, stress, nonnegative path, and positive parameters are required.');

old_energy=sum(0.5*moduli_MPa.*old_strain.^2);
if path_increment==0
    strain=old_strain;
    decay=ones(size(strain));
    tangent=zeros(size(strain));
else
    exponent=moduli_MPa*path_increment./resistances_MPa;
    decay=exp(-exponent);
    equilibrium=sigma_MPa./moduli_MPa;
    strain=equilibrium+(old_strain-equilibrium).*decay;
    tangent=(1-decay)./moduli_MPa;
end

increment=strain-old_strain;
force=sigma_MPa-moduli_MPa.*strain;
new_energy=sum(0.5*moduli_MPa.*strain.^2);
work=sigma_MPa*sum(increment);
dissipation=work-(new_energy-old_energy);
identity=sum(force.*increment+0.5*moduli_MPa.*increment.^2);
identity_defect=dissipation-identity;
if path_increment==0
    exact_map_residual=zeros(size(strain));
else
    equilibrium=sigma_MPa./moduli_MPa;
    exact_map_residual=strain-(equilibrium+ ...
        (old_strain-equilibrium).*decay);
end

audit=struct('effective_strain',sum(strain), ...
    'increment',increment,'force_MPa',force, ...
    'path_increment',path_increment,'decay',decay, ...
    'stress_tangent_per_MPa',sum(tangent), ...
    'old_stored_energy_MPa',old_energy, ...
    'new_stored_energy_MPa',new_energy, ...
    'accommodation_work_MPa',work, ...
    'dissipation_MPa',dissipation, ...
    'energy_identity_defect_MPa',identity_defect, ...
    'exact_map_residual',exact_map_residual, ...
    'observation_accessed',false,'production_connected',false);
scale=max(1,abs(work)+abs(new_energy-old_energy)+abs(dissipation));
assert(max(abs(exact_map_residual))<=5e-15 && ...
    dissipation>=-2e-12 && abs(identity_defect)<=5e-12*scale, ...
    'sma:candidate_transformation_path_accommodation_1d:Energy', ...
    'Path accommodation violates its exact map or energy contract.');
end
