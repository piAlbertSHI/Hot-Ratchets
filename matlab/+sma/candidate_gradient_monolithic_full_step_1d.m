function [phase,plastic,audit]=candidate_gradient_monolithic_full_step_1d( ...
    p,old_phase,old_plastic,macro_strain,T,dt,closure,plastic_closure,guess)
%SMA.CANDIDATE_GRADIENT_MONOLITHIC_FULL_STEP_1D Spatial Zhang full step.
% Direct Zhang history closes the monolithic phase solve from committed
% plastic state. ARP/TRIP is then iterated to total-extension consistency.

if nargin<9 || isempty(guess), guess=struct(); end
n=numel(old_phase); assert(iscell(old_phase) && iscell(old_plastic) && ...
    numel(old_plastic)==n,'Matching phase/plastic cell arrays are required.');
source_branch_envelope=get_option(closure,'source_branch_envelope',struct());
branch_bound=isstruct(source_branch_envelope) && ...
    isfield(source_branch_envelope,'semantic_card_id');
w=expand(closure.weights,n); xi_recent=expand(closure.xi_recent,n);
residual_event_policy=char(get_option(plastic_closure, ...
    'residual_m_event_policy','clip_legacy'));
event_boundary_mode=strcmpi(residual_event_policy,'event_boundary');
if event_boundary_mode
    direction_event=expand(closure.direction_M,n);
    event_xi_lower=cellfun(@(ph,pl,direction) ...
        residual_event_lower_bound(ph,pl,direction,plastic_closure), ...
        old_phase(:),old_plastic(:),num2cell(direction_event));
else
    event_xi_lower=[];
end
for i=1:n
    assert(abs(old_phase{i}.xi_M-old_plastic{i}.xi_M)<=1e-13, ...
        'Committed phase and plastic states must share xi_M in every cell.');
end
old_plastic_strain=cellfun(@plastic_strain,old_plastic(:));
control_mode=char(get_option(closure,'candidate_mechanical_control','prescribed_strain'));
assert(any(strcmp(control_mode,{'prescribed_strain','validation_prescribed_stress'})), ...
    'Unknown candidate mechanical control owner.');
stress_control=strcmp(control_mode,'validation_prescribed_stress');
effective_target=macro_strain-w.'*old_plastic_strain;
if isfield(guess,'effective_target') && isfinite(guess.effective_target)
    effective_target=guess.effective_target;
end
phase_guess=[]; if isfield(guess,'phase'), phase_guess=guess.phase; end
plastic_guess=cell(n,1); if isfield(guess,'plastic'), plastic_guess=guess.plastic; end
relaxation=get_option(closure,'plastic_fixed_point_relaxation',0.6);
max_iterations=get_option(closure,'plastic_fixed_point_iterations',60);
tol=get_option(closure,'plastic_fixed_point_tolerance',2e-10);
coupling_mode=lower(char(get_option(closure, ...
    'residual_martensite_coupling','committed_split')));
assert(any(strcmp(coupling_mode,{'committed_split','same_trial_fixed_point', ...
    'same_trial_full_history'})), ...
    'Unknown residual-martensite coupling mode: %s.',coupling_mode);
same_trial_history_owner=lower(char(get_option(closure, ...
    'same_trial_history_owner','committed_source')));
assert(any(strcmp(same_trial_history_owner,{'committed_source','trial_local_max'})), ...
    'Unknown same-trial history owner: %s.',same_trial_history_owner);
if strcmp(same_trial_history_owner,'trial_local_max')
    assert(~strcmp(coupling_mode,'committed_split'), ...
        'Trial-local history owner is validation-only for same-trial coupling.');
end
history_relaxation=get_option(closure, ...
    'residual_martensite_fixed_point_relaxation',relaxation);
history_tol=get_option(closure, ...
    'residual_martensite_fixed_point_tolerance',tol);
assert(isfinite(history_relaxation) && history_relaxation>0 && ...
    history_relaxation<=1 && isfinite(history_tol) && history_tol>0, ...
    'Residual-martensite fixed-point controls are inadmissible.');
xi_res_iter=cellfun(@(s)s.xi_Mr,old_plastic(:));
xi_recent_iter=xi_recent;
omega_iter=cellfun(@(s)s.Omega,old_plastic(:));
yp_iter=cellfun(@(s)s.Yp,old_plastic(:));
deta_iter=cellfun(@(s)s.DeltaEtaP_MPaK,old_plastic(:));
if isfield(guess,'xi_res') && ~isempty(guess.xi_res)
    xi_res_iter=expand(guess.xi_res,n);
end
if isfield(guess,'history') && ~isempty(guess.history)
    hguess=guess.history;
    if isfield(hguess,'Omega'), omega_iter=expand(hguess.Omega,n); end
    if isfield(hguess,'Yp'), yp_iter=expand(hguess.Yp,n); end
    if isfield(hguess,'DeltaEtaP_MPaK')
        deta_iter=expand(hguess.DeltaEtaP_MPaK,n);
    end
end
converged=false;
history_full_fixed_norm=Inf;
for iteration=1:max_iterations
    pc=closure;
    if event_boundary_mode
        pc.residual_event_xi_M_lower=event_xi_lower;
        pc.residual_event_boundary_tolerance= ...
            get_option(plastic_closure,'residual_event_boundary_tolerance',2e-9);
    end
    eq39_ablation=get_option(closure,'eq39_ablation',canonical_eq39_ablation());
    if eq39_ablation.enabled
        pc.transformation_exponent_R=eq39_ablation.m_R;
        pc.transformation_exponent_M=eq39_ablation.m_M;
        pc.transformation_reference_rate_per_s=eq39_ablation.reference_rate_per_s;
    end
    if strcmp(coupling_mode,'committed_split')
        pc.xi_res=cellfun(@(s)s.xi_Mr,old_plastic(:));
    else
        pc.xi_res=xi_res_iter;
    end
    if strcmp(same_trial_history_owner,'trial_local_max')
        % Zhang's recent-M history is an owned monotone trial variable in
        % this diagnostic branch.  It is advanced from the same trial
        % iterate; it is never clipped to a committed value or inferred
        % from an experimental endpoint.
        xi_recent_iter=max(xi_recent_iter,pc.xi_res);
        pc.xi_recent=xi_recent_iter;
    end
    pc.Btr_MPa=zeros(n,1); pc.delta_eta_p_MPaK=zeros(n,1);
    pc.Y_M_base_MPa=zeros(n,1);
    pc.require_zhang_source_receipt=true;
    pc.Y_M_threshold_receipt=cell(n,1);
    pc.require_history_state_receipt=true;
    pc.history_state_receipt=cell(n,1);
    pc.residual_tolerance=get_option(closure,'phase_residual_tolerance',2e-7);
    directionM=expand(pc.direction_M,n);
    for i=1:n
        NB=sign(old_plastic{i}.eps_p_AR); if NB==0, NB=directionM(i); end
        if strcmp(coupling_mode,'same_trial_full_history')
            omega_used=omega_iter(i);
            yp_used=yp_iter(i);
            deta_used=deta_iter(i);
        else
            omega_used=old_plastic{i}.Omega;
            yp_used=old_plastic{i}.Yp;
            deta_used=old_plastic{i}.DeltaEtaP_MPaK;
        end
        pc.Btr_MPa(i)=omega_used*NB;
        pc.delta_eta_p_MPaK(i)=deta_used;
        [pc.Y_M_base_MPa(i),pc.Y_M_threshold_audit{i}]= ...
            sma.candidate_zhang_kinetic_threshold_1d( ...
            p,pc.xi_recent(i),yp_used);
        threshold=pc.Y_M_threshold_audit{i};
        if eq39_ablation.enabled
            source_role='non_source_eq39_ablation';
            source_name='validation_only_counterfactual_m_branch';
            receipt_exponent=eq39_ablation.m_M;
            receipt_source_authoritative=false;
        else
            source_role='kinetic_threshold';
            source_name=threshold.source;
            receipt_exponent=threshold.transformation_exponent;
            receipt_source_authoritative=true;
        end
        pc.Y_M_threshold_receipt{i}=struct( ...
            'material_case_id',p.case_id, ...
            'xi_recent',pc.xi_recent(i),'Yp_MPa',yp_used, ...
            'Yf_MPa',threshold.Yf0_MPa+threshold.d_MPa* ...
                pc.xi_recent(i)^threshold.n_xi, ...
            'Y_M_base_MPa',pc.Y_M_base_MPa(i), ...
            'formula_id','Zhang_Eq39_Yf_minus_Yp', ...
            'source_role',source_role, ...
            'source_card_id',threshold.source_card_id, ...
            'Yf0_MPa',threshold.Yf0_MPa,'d_MPa',threshold.d_MPa, ...
            'n_xi',threshold.n_xi, ...
            'source_transformation_exponent',threshold.transformation_exponent, ...
            'source_reference_rate_per_s',threshold.reference_rate_per_s, ...
            'exponent',receipt_exponent, ...
            'reference_rate_per_s',threshold.reference_rate_per_s, ...
            'source',source_name,'source_authoritative',receipt_source_authoritative, ...
            'ablation_id',eq39_ablation.ablation_id, ...
            'parent_source_receipt_digest',eq39_ablation.parent_source_receipt_digest);
        if branch_bound
            pc.Y_M_threshold_receipt{i}=attach_source_branch_fields( ...
                pc.Y_M_threshold_receipt{i},source_branch_envelope);
        end
        history=struct( ...
            'material_case_id',p.case_id, ...
            'history_owner','candidate_gradient_monolithic_full_step_1d', ...
            'xi_Mr',pc.xi_res(i), ...
            'xi_recent',pc.xi_recent(i), ...
            'history_lineage_owner',same_trial_history_owner, ...
            'Omega_MPa',omega_used, ...
            'Yp_MPa',yp_used, ...
            'DeltaEtaP_MPaK',deta_used, ...
            'Btr_MPa',pc.Btr_MPa(i), ...
            'Yf_MPa',pc.Y_M_threshold_receipt{i}.Yf_MPa, ...
            'Y_M_base_MPa',pc.Y_M_base_MPa(i), ...
            'source_card_id',threshold.source_card_id, ...
            'Yf0_MPa',threshold.Yf0_MPa,'d_MPa',threshold.d_MPa, ...
            'n_xi',threshold.n_xi, ...
            'source_transformation_exponent',threshold.transformation_exponent, ...
            'source_reference_rate_per_s',threshold.reference_rate_per_s, ...
            'formula_id','Zhang_Eq39_Yf_minus_Yp', ...
            'history_constants',struct( ...
            'a1',get_option(plastic_closure,'zhang_a1',0.6), ...
            'a2',get_option(plastic_closure,'zhang_a2',0.1), ...
            'cOmega_MPa',get_option(plastic_closure,'zhang_cOmega_MPa',92.0), ...
            'cxi_sqrt_m',get_option(plastic_closure,'zhang_cxi_sqrt_m',3.5e-8), ...
            'etaM_N_per_K',get_option(plastic_closure,'zhang_etaM_N_per_K',1.23e-9), ...
            'etaA_N_per_K',get_option(plastic_closure,'zhang_etaA_N_per_K',1.0e-9), ...
            'cY_MPa',get_option(plastic_closure,'zhang_cY_MPa',4.5)));
        history.eq39_ablation_id=eq39_ablation.ablation_id;
        history.eq39_exponent=receipt_exponent;
        if branch_bound
            history=attach_source_branch_fields(history,source_branch_envelope);
        end
        history.history_state_token=history_token(history);
        pc.history_state_receipt{i}=history;
    end
    resistance_multiplier=expand(get_option(pc,'resistance_multiplier',1),n);
    assert(all(pc.Y_M_base_MPa.*resistance_multiplier+ ...
        expand(pc.resistance_shift_MPa,n)>0), ...
        'Direct Zhang Y=Yf-Yp plus frozen resistance must remain positive.');
    [phase_trial,phase_audit]=sma.candidate_gradient_monolithic_phase_step_1d( ...
        p,old_phase,effective_target,T,dt,pc,phase_guess);
    phase_guess=[phase_audit.stress_MPa;phase_audit.delta_lambda_R; ...
        phase_audit.delta_lambda_M];
    plastic_trial=cell(n,1); plastic_audit=cell(n,1);
    for i=1:n
        [plastic_trial{i},plastic_audit{i}]=sma.candidate_arp_trip_inheritance_1d( ...
            old_plastic{i},phase_trial{i}.xi_M,phase_audit.stress_MPa,dt, ...
            plastic_closure,plastic_guess{i});
        plastic_guess{i}=[plastic_audit{i}.delta_gamma_arp_local; ...
            plastic_audit{i}.delta_gamma_trip_local];
    end
    pstrain=cellfun(@plastic_strain,plastic_trial);
    if stress_control
        % Under force control strain is a computed response. Plastic strain
        % must not trigger repeated phase solves to enforce a fake target.
        effective_target=phase_audit.terms.macro_strain;
        target_new=effective_target;
        fixed=0;
    else
        target_new=macro_strain-w.'*pstrain;
        fixed=target_new-effective_target;
    end
    xi_res_new=cellfun(@(s)s.xi_Mr,plastic_trial);
    if strcmp(same_trial_history_owner,'trial_local_max')
        xi_recent_iter=max(xi_recent_iter,xi_res_new);
        xi_recent_iter=max(xi_recent_iter,cellfun(@(s)s.xi_M,phase_trial));
    end
    history_fixed=xi_res_new-pc.xi_res;
    history_fixed_norm=max(abs(history_fixed));
    if strcmp(coupling_mode,'same_trial_full_history')
        omega_new=cellfun(@(s)s.Omega,plastic_trial(:));
        yp_new=cellfun(@(s)s.Yp,plastic_trial(:));
        deta_new=cellfun(@(s)s.DeltaEtaP_MPaK,plastic_trial(:));
        history_full_delta=[xi_res_new-xi_res_iter; omega_new-omega_iter; ...
            yp_new-yp_iter; deta_new-deta_iter];
        history_full_scale=max(1,[abs(xi_res_iter); abs(omega_iter); ...
            abs(yp_iter); abs(deta_iter)]);
        history_full_fixed_norm=max(abs(history_full_delta)./history_full_scale);
    else
        omega_new=[]; yp_new=[]; deta_new=[];
        history_full_delta=[]; history_full_scale=[];
        history_full_fixed_norm=history_fixed_norm;
    end
    history_ok=strcmp(coupling_mode,'committed_split') || ...
        (strcmp(coupling_mode,'same_trial_fixed_point') && ...
        history_fixed_norm<=history_tol) || ...
        (strcmp(coupling_mode,'same_trial_full_history') && ...
        history_full_fixed_norm<=history_tol);
    if abs(fixed)<=tol && history_ok
        converged=true;
        break;
    end
    effective_target=effective_target+relaxation*fixed;
    if strcmp(coupling_mode,'same_trial_fixed_point')
        xi_res_iter=xi_res_iter+history_relaxation*history_fixed;
        xi_res_iter=min(max(xi_res_iter,0),1);
    elseif strcmp(coupling_mode,'same_trial_full_history')
        xi_res_iter=xi_res_iter+history_relaxation*(xi_res_new-xi_res_iter);
        omega_iter=omega_iter+history_relaxation*(omega_new-omega_iter);
        yp_iter=yp_iter+history_relaxation*(yp_new-yp_iter);
        deta_iter=deta_iter+history_relaxation*(deta_new-deta_iter);
        xi_res_iter=min(max(xi_res_iter,0),1);
    end
end
assert(converged, ...
    ['Monolithic phase--ARP/TRIP fixed point failed; strain residual %.6g, ' ...
    'residual-M history residual %.6g, full-history residual %.6g in mode %s.'], ...
    abs(fixed),history_fixed_norm,history_full_fixed_norm,coupling_mode);
phase=phase_trial; plastic=plastic_trial;
reconstructed=phase_audit.terms.macro_strain+w.'*pstrain;
if stress_control, macro_strain=reconstructed; end
outer=macro_strain-reconstructed;
plastic_residual=max(cellfun(@(a)a.local_residual_norm,plastic_audit));
plastic_conservation=max(cellfun(@(a)abs(a.plastic_conservation_error),plastic_audit));
slip_conservation=max(cellfun(@(a)abs(a.slip_conservation_error),plastic_audit));
rho_balance=max(cellfun(@(a)abs(a.rho_balance_error),plastic_audit));
audit=struct('stress_MPa',phase_audit.stress_MPa,'phase',phase_audit, ...
    'plastic',{plastic_audit},'plastic_strain',pstrain, ...
    'effective_target',effective_target,'reconstructed_strain',reconstructed, ...
    'outer_strain_residual',outer,'fixed_point_residual',fixed, ...
    'max_plastic_residual',plastic_residual, ...
    'max_plastic_conservation_error',plastic_conservation, ...
    'max_slip_conservation_error',slip_conservation, ...
    'max_rho_balance_error',rho_balance,'iterations',iteration, ...
    'residual_martensite_coupling',coupling_mode, ...
    'same_trial_history_owner',same_trial_history_owner, ...
    'xi_recent_trial_owner',xi_recent_iter, ...
    'xi_res_used',pc.xi_res,'xi_Mr_accepted',xi_res_new, ...
    'residual_martensite_fixed_point_residual',history_fixed, ...
    'max_residual_martensite_fixed_point_residual',history_fixed_norm, ...
    'history_full_fixed_point_residual',history_full_delta, ...
    'max_history_full_fixed_point_residual',history_full_fixed_norm, ...
    'history_full_fixed_point_scale',history_full_scale, ...
    'history_full_iterate',struct('xi_Mr',xi_res_iter,'Omega',omega_iter, ...
        'Yp',yp_iter,'DeltaEtaP_MPaK',deta_iter), ...
    'residual_martensite_fixed_point_tolerance',history_tol, ...
    'xi_Mr_target_unclipped',cellfun(@(a)a.xi_Mr_target_unclipped,plastic_audit), ...
    'xi_Mr_target_clipped',cellfun(@(a)a.xi_Mr_target_clipped,plastic_audit), ...
    'xi_Mr_target_clip_active',cellfun(@(a)a.xi_Mr_target_clip_active,plastic_audit), ...
    'xi_Mr_upper_clamp_active',cellfun(@(a)a.xi_Mr_upper_clamp_active,plastic_audit), ...
    'Y_M_threshold_audit',{pc.Y_M_threshold_audit}, ...
    'history_state_receipt',{pc.history_state_receipt}, ...
    'outer_strain_tolerance',max(5e-9,p.Hmax_i* ...
        get_option(closure,'phase_residual_tolerance',2e-7)), ...
    'eq39_ablation',eq39_ablation, ...
    'residual_event_policy',residual_event_policy, ...
    'residual_event_boundary_mode',event_boundary_mode, ...
    'residual_event_xi_M_lower',event_xi_lower, ...
    'residual_event_boundary_active',event_boundary_mode && ...
        isfield(phase_audit,'residual_event_boundary_active') && ...
        logical(phase_audit.residual_event_boundary_active), ...
    'observation_accessed',false,'production_connected',false);
if stress_control
    audit.mechanical_control_owner=control_mode;
    audit.strain_is_computed_response=true;
    audit.strain_control_enforced=false;
    audit.prescribed_stress_MPa=closure.candidate_target_stress_MPa;
    audit.prescribed_stress_residual_MPa= ...
        phase_audit.stress_MPa-closure.candidate_target_stress_MPa;
    assert(abs(audit.prescribed_stress_residual_MPa)<= ...
        get_option(closure,'stress_control_tolerance_MPa',2e-7), ...
        'Direct stress-control residual exceeded the original stress gate.');
end
assert(abs(outer)<=audit.outer_strain_tolerance && plastic_residual<=2e-9, ...
    ['Accepted monolithic full step violates constitutive compatibility: ' ...
    'outer %.9g, plastic %.9g.'],outer,plastic_residual);
end

function xi_lower=residual_event_lower_bound(phase,plastic,direction,closure)
xi_lower=plastic.xi_Mr;
if direction>=0 || phase.xi_M<=plastic.xi_Mr+2e-12
    return;
end
a1=get_option(closure,'zhang_a1',0.6);
cxi=get_option(closure,'zhang_cxi_sqrt_m',3.5e-8);
target=cxi*sqrt(max(plastic.rho_M,0));
xi_old=phase.xi_M; r_old=plastic.xi_Mr;
f=@(d)(xi_old-d)- ...
    (target+(r_old-target)*exp(-a1*d));
f0=f(0); f1=f(xi_old);
if ~(f0>0 && f1<0)
    return;
end
lo=0; hi=xi_old;
for k=1:100
    mid=0.5*(lo+hi); fm=f(mid);
    if abs(fm)<=1e-14*max(1,xi_old), lo=mid; hi=mid; break; end
    if f0*fm>0, lo=mid; f0=fm; else, hi=mid; f1=fm; end
end
xi_lower=xi_old-0.5*(lo+hi);
end

function value=plastic_strain(s)
value=s.xi_M*s.eps_p_M+(1-s.xi_M)*s.eps_p_AR;
end

function value=expand(value,n)
if isscalar(value), value=repmat(value,n,1); else, value=value(:); end
assert(numel(value)==n && all(isfinite(value)),'One finite value per cell is required.');
end

function value=get_option(s,name,default)
if isfield(s,name), value=s.(name); else, value=default; end
end

function token=history_token(receipt)
% Readable deterministic identity; this is not used as a cryptographic hash.
ablation_id='canonical'; exponent=200;
if isfield(receipt,'eq39_ablation_id'), ablation_id=receipt.eq39_ablation_id; end
if isfield(receipt,'eq39_exponent'), exponent=receipt.eq39_exponent; end
token=sprintf(['gradient_history_v2|case=%d|xi_Mr=%.17g|Omega=%.17g|Yp=%.17g|' ...
    'deta_p=%.17g|Btr=%.17g|Yf=%.17g|Ybase=%.17g|card=%s|formula=%s'], ...
    receipt.material_case_id,receipt.xi_Mr,receipt.Omega_MPa,receipt.Yp_MPa, ...
    receipt.DeltaEtaP_MPaK,receipt.Btr_MPa,receipt.Yf_MPa,receipt.Y_M_base_MPa, ...
    receipt.source_card_id,receipt.formula_id);
token=sprintf('%s|eq39_m=%.17g|ablation=%s',token,exponent,ablation_id);
if isfield(receipt,'source_semantic_card_id')
    token=sprintf('%s|branch=%s',token,receipt.source_semantic_card_id);
end
end

function receipt=attach_source_branch_fields(receipt,envelope)
receipt.source_branch_id=envelope.branch_id;
receipt.source_semantic_card_id=envelope.semantic_card_id;
receipt.source_branch_card_digest=envelope.card_payload_digest;
receipt.source_branch_authority=envelope.authority_class;
receipt.source_branch_validation_only=envelope.validation_only;
receipt.source_branch_promotion_allowed=envelope.promotion_allowed;
end

function a=canonical_eq39_ablation()
a=struct('enabled',false,'m_M',200,'m_R',200,'reference_rate_per_s',1, ...
    'ablation_id','canonical','parent_source_receipt_digest','canonical', ...
    'source_authoritative',true,'production_connected',false, ...
    'experimental_acceptance',false,'observation_accessed',false, ...
    'experimental_backfill',false,'tag_suffix','canonical');
end
