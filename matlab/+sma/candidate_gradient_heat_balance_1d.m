function [T_balance,audit]=candidate_gradient_heat_balance_1d( ...
    p,T_old,T_probe,sigma_old,phase_audit,plastic_audit,dt,closure)
%SMA.CANDIDATE_GRADIENT_HEAT_BALANCE_1D Local Zhang heat and conduction.
% Gradient energy is conservative and is deliberately absent from heat.

n=numel(T_old); T_old=T_old(:); T_probe=T_probe(:);
assert(numel(T_probe)==n && numel(plastic_audit)==n && ...
    all(isfinite([T_old;T_probe])) && isfinite(sigma_old) && dt>0, ...
    'Thermal grid inputs are inadmissible.');
required={'gauge_length_m','axial_conductivity_W_mK', ...
    'surface_heat_loss_rate_WkgK','ambient_temperature_K'};
assert(all(isfield(closure,required)),'Thermal grid closure is incomplete.');
dx=closure.gauge_length_m/n;
[Dxx,~,operator]=sma.candidate_neumann_laplacian_1d(n,dx);
conv=1e6/p.rho; Tbar=0.5*(T_old+T_probe);
dR=phase_audit.delta_lambda_R; dM=phase_audit.delta_lambda_M;
terms=phase_audit.terms;
assert(isfield(terms,'pi_R_MPa') && isfield(terms,'pi_M_MPa') && ...
    numel(terms.pi_R_MPa)==n && numel(terms.pi_M_MPa)==n && ...
    all(isfinite([terms.pi_R_MPa(:);terms.pi_M_MPa(:)])), ...
    'Eq.(46) requires finite same-trial thermodynamic driving forces pi_R/pi_M.');
% Zhang Eq.(46) uses the thermodynamic driving forces pi^tr multiplied by
% the accepted transformation increments.  The kinetic terms Y*q from
% Eq.(39) are residual-side rate contributions and are not interchangeable
% heat sources, even though they coincide at an active ideal root.
Q_RT=terms.pi_R_MPa.*dR*conv;
Q_MT=terms.pi_M_MPa.*dM*conv;
Q_ARP=zeros(n,1); Q_TRIP=zeros(n,1);
for i=1:n
    pa=plastic_audit{i};
    assert(isfield(pa.terms,'signed_drive_arp_MPa') && ...
        isfield(pa.terms,'signed_drive_trip_MPa') && ...
        isfield(pa.terms,'N_arp') && isfield(pa.terms,'N_trip'), ...
        'Eq.(46) ARP/TRIP heat terms require signed normal receipts.');
    Q_ARP(i)=pa.terms.signed_drive_arp_MPa*pa.free_zone* ...
        pa.delta_gamma_arp_local*conv;
    Q_TRIP(i)=pa.terms.signed_drive_trip_MPa*pa.mu* ...
        pa.delta_gamma_trip_local*conv;
end
Q_RT_latent=-Tbar*p.R_entropy.*dR*conv;
Q_MT_latent=-Tbar.*terms.delta_eta_mix_MPaK.*dM*conv;
Q_thermoelastic=-p.alphaA*Tbar*(phase_audit.stress_MPa-sigma_old)*conv;
Q_internal=Q_RT+Q_MT+Q_ARP+Q_TRIP+Q_RT_latent+Q_MT_latent+Q_thermoelastic;
Q_conduction=dt*closure.axial_conductivity_W_mK/p.rho*(Dxx*T_probe);
Q_surface=dt*closure.surface_heat_loss_rate_WkgK* ...
    (T_probe-closure.ambient_temperature_K);
T_balance=T_old+(Q_internal+Q_conduction-Q_surface)/p.cp;
first_law=p.cp*(T_balance-T_old)-Q_internal-Q_conduction+Q_surface;
audit=struct('Q_RT_diss_Jkg',Q_RT,'Q_MT_diss_Jkg',Q_MT, ...
    'Q_ARP_diss_Jkg',Q_ARP,'Q_TRIP_diss_Jkg',Q_TRIP, ...
    'Q_RT_latent_Jkg',Q_RT_latent,'Q_MT_latent_Jkg',Q_MT_latent, ...
    'Q_thermoelastic_Jkg',Q_thermoelastic, ...
    'Q_internal_total_Jkg',Q_internal,'Q_conduction_Jkg',Q_conduction, ...
    'Q_surface_loss_Jkg',Q_surface,'first_law_defect_Jkg',first_law, ...
    'max_first_law_defect_Jkg',max(abs(first_law)), ...
    'minimum_dissipation_Jkg',min([Q_RT;Q_MT;Q_ARP;Q_TRIP]), ...
    'mechanical_heat_force_source','pi_R_MPa/pi_M_MPa_same_trial', ...
    'kinetic_rate_terms_excluded_from_heat',true, ...
    'arp_trip_heat_force_source','sigma*N_arp-tau_p / (sigma+beta)*N_trip-tau_p', ...
    'operator',operator,'observation_accessed',false, ...
    'production_connected',false);
assert(audit.minimum_dissipation_Jkg>=-1e-8 && ...
    audit.max_first_law_defect_Jkg<=1e-9, ...
    'Local thermal dissipation or first-law contract failed.');
end
