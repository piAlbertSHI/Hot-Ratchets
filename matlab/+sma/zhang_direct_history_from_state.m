history=struct('xi',state.xi,'xi_Mr',state.zhang_xi_Mr, ...
    'rho_M',state.zhang_rho_M,'rho_AR',state.zhang_rho_AR, ...
    'D_M',state.zhang_D_M,'D_AR',state.zhang_D_AR, ...
    'DeltaEtaP',state.zhang_DeltaEtaP,'Omega',state.zhang_Omega, ...
    'Yp',state.zhang_Yp,'Lambda_M',state.zhang_Lambda_M);
end
