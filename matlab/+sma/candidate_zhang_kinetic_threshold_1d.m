function [Y_M,audit]=candidate_zhang_kinetic_threshold_1d(p,xi_recent,Yp)
%SMA.CANDIDATE_ZHANG_KINETIC_THRESHOLD_1D Zhang Eqs. (54)--(56).
% Return the NiTi source-card kinetic threshold Y=Yf-Yp used by Eq. (39).
% This is deliberately separate from the tau_AR<->M resistance in
% Eqs. (61)--(63); the two surfaces must never be silently interchanged.

if nargin<3 || isempty(Yp), Yp=0.0; end
assert(isfield(p,'case_id') && p.case_id==1, ...
    'sma:candidate_zhang_kinetic_threshold_1d:UnsupportedCard', ...
    'The Zhang kinetic-threshold adapter is restricted to the NiTi source card.');
assert(isscalar(xi_recent) && isfinite(xi_recent) && xi_recent>=0 && xi_recent<=1, ...
    'sma:candidate_zhang_kinetic_threshold_1d:InvalidXi', ...
    'xi_recent must be a finite fraction in [0,1].');
assert(isscalar(Yp) && isfinite(Yp) && Yp>=0, ...
    'sma:candidate_zhang_kinetic_threshold_1d:InvalidYp', ...
    'Yp must be a finite nonnegative threshold loss.');

% Zhang Table 2 / Eqs. (54)--(56): Yf0=21.7 MPa, d=2.8 MPa,
% n_xi=5. These values are owned by the source material card, rather than
% being function-local literals.  This prevents a conditional branch from
% changing the threshold while retaining the same transaction identity.
required_card_fields={'zhang_Yf0_MPa','zhang_Y_d_MPa','zhang_Y_n_xi', ...
    'zhang_m_tr','zhang_reference_rate_per_s'};
for k=1:numel(required_card_fields)
    assert(isfield(p,required_card_fields{k}), ...
        'sma:candidate_zhang_kinetic_threshold_1d:MissingSourceCardField', ...
        'NiTi source card is missing %s.',required_card_fields{k});
end
Yf0_MPa=p.zhang_Yf0_MPa;
d_MPa=p.zhang_Y_d_MPa;
n_xi=p.zhang_Y_n_xi;
m_tr=p.zhang_m_tr;
reference_rate_per_s=p.zhang_reference_rate_per_s;
assert(isfinite(Yf0_MPa) && Yf0_MPa>=0 && isfinite(d_MPa) && d_MPa>=0 && ...
    isfinite(n_xi) && n_xi>=1 && isfinite(m_tr) && m_tr>=1 && ...
    isfinite(reference_rate_per_s) && reference_rate_per_s>0, ...
    'sma:candidate_zhang_kinetic_threshold_1d:InvalidSourceCard', ...
    'NiTi source-card Eq. (39) kinetics are not admissible.');
Yf=Yf0_MPa+d_MPa*xi_recent^n_xi;
Y_M=Yf-Yp;
assert(isfinite(Y_M) && Y_M>0, ...
    'sma:candidate_zhang_kinetic_threshold_1d:NonPositiveThreshold', ...
    'The Zhang Eq. (39) kinetic threshold must remain positive.');

audit=struct('Yf0_MPa',Yf0_MPa,'d_MPa',d_MPa,'n_xi',n_xi, ...
    'xi_recent',xi_recent,'Yp_MPa',Yp,'Y_M_MPa',Y_M, ...
    'source','Zhang_Table2_Eqs54_56', ...
    'source_card_id','niti_zhang2022_table2', ...
    'transformation_exponent',m_tr, ...
    'reference_rate_per_s',reference_rate_per_s, ...
    'observation_accessed',false,'production_connected',false);
end
