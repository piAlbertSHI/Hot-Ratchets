function [trial,receipt] = candidate_yuan_reduced_material_step_1d( ...
    p,state,control,Tamb,dt)
%SMA.CANDIDATE_YUAN_REDUCED_MATERIAL_STEP_1D
% Isolated Cu-Al-Mn reduced-model step with explicit provenance limits.
%
% The mechanics/thermal kernel is the project's legacy generic 1D model.
% It is useful for protocol and state diagnostics, but it is not a
% source-authoritative Yuan constitutive law.  Engineering strain-rate input
% is mapped explicitly to the solver logarithmic strain coordinate.

if nargin<5 || isempty(dt), dt=p.default_dt; end
if nargin<4 || isempty(Tamb), Tamb=p.Tamb; end
assert(any(p.case_id==[2,3,4]), ...
    'sma:candidate_yuan_reduced_material_step_1d:MaterialRole', ...
    'This reduced provider accepts only Yuan Cu-Al-Mn cards.');
assert(isstruct(control) && isfield(control,'mode'), ...
    'sma:candidate_yuan_reduced_material_step_1d:Control', ...
    'A declared control mode is required.');
assert(isfinite(dt) && isscalar(dt) && dt>0 && isfinite(Tamb), ...
    'sma:candidate_yuan_reduced_material_step_1d:Time', ...
    'Time step and ambient temperature must be finite and dt positive.');
assert_zhang_extensions_neutral(p);

case_name = canonical_case_name(p.case_id);
provenance = sma.yuan_material_card_provenance(case_name,p);
mode = char(string(control.mode));
engineering_strain_old = exp(state.eps)-1;
engineering_strain_target = engineering_strain_old;
if strcmp(mode,'engineering_strain_rate')
    assert(isfield(control,'signed_rate_1_per_s') && ...
        isfinite(control.signed_rate_1_per_s) && ...
        isscalar(control.signed_rate_1_per_s), ...
        'sma:candidate_yuan_reduced_material_step_1d:Control', ...
        'Engineering strain-rate control requires a finite signed rate.');
    engineering_strain_target = engineering_strain_old+ ...
        control.signed_rate_1_per_s*dt;
    assert(engineering_strain_target>-1, ...
        'sma:candidate_yuan_reduced_material_step_1d:Control', ...
        'Engineering strain target must exceed -1.');
    solver_target = log1p(engineering_strain_target);
    [trial,aux] = sma.coupled_step_1d( ...
        p,state,1,solver_target,Tamb,dt);
    control_residual = trial.eps-solver_target;
elseif strcmp(mode,'stress_hold')
    assert(isfield(control,'target_stress_MPa') && ...
        isfinite(control.target_stress_MPa) && ...
        isscalar(control.target_stress_MPa), ...
        'sma:candidate_yuan_reduced_material_step_1d:Control', ...
        'Stress hold requires a finite scalar stress target.');
    solver_target = control.target_stress_MPa;
    [trial,aux] = sma.coupled_step_1d( ...
        p,state,0,solver_target,Tamb,dt);
    control_residual = trial.sigma-solver_target;
else
    error('sma:candidate_yuan_reduced_material_step_1d:Control', ...
        'Unsupported control mode: %s.',mode);
end

state_vector = sma.state_vector_1d(trial);
assert(all(isfinite(state_vector)), ...
    'sma:candidate_yuan_reduced_material_step_1d:State', ...
    'Reduced Yuan trial state is not finite.');
thermal_defect = NaN;
if all(isfield(aux,{'latent_specific_Jkg','dissipation_specific_Jkg', ...
        'heat_loss_specific_Jkg'}))
    thermal_defect = p.cp*(trial.T-state.T)-(aux.latent_specific_Jkg+ ...
        aux.dissipation_specific_Jkg-aux.heat_loss_specific_Jkg);
end

receipt = struct('schema_id','yuan_reduced_material_step_v1', ...
    'accepted',true,'candidate_only',true,'state_commit',false, ...
    'production_connected',false,'source_authoritative_complete',false, ...
    'experimental_acceptance',false,'observation_accessed',false, ...
    'material_card_id',case_name, ...
    'material_model_role',provenance.material_model_role, ...
    'parameter_provenance_status',provenance.parameter_provenance_status, ...
    'source_cp_mismatch',provenance.source_cp_mismatch, ...
    'control_mode',mode,'dt_s',dt,'ambient_temperature_K',Tamb, ...
    'engineering_strain_old',engineering_strain_old, ...
    'engineering_strain_target',engineering_strain_target, ...
    'solver_log_strain_target',solver_target, ...
    'stress_MPa',trial.sigma,'temperature_K',trial.T, ...
    'martensite_fraction',trial.xi, ... % legacy field; see semantics below
    'reaction_extent_normalized',trial.xi, ...
    'inventory_semantics','normalized_reaction_not_measured_phase', ...
    'martensite_fraction_is_observation',false, ...
    'control_residual',control_residual, ...
    'constitutive_residual',aux.residual_norm, ...
    'thermal_balance_defect_Jkg',thermal_defect, ...
    'strain_measure_mapping','engineering_to_logarithmic_log1p', ...
    'full_phase_root',false,'full_thermal_root',false, ...
    'aux',aux);
end

function assert_zhang_extensions_neutral(p)
names = {'enable_r_phase','enable_explicit_r_phase_state', ...
    'enable_r_phase_return_map','enable_composition_weighted_mt', ...
    'enable_zhang_source_mt_resistance','zhang_direct_Yp_coupling', ...
    'zhang_direct_Omega_coupling','enable_mt_dissipation_evolution', ...
    'enable_mt_nonlinear_hardening','Y_activity_population_mix', ...
    'enable_residual_martensite'};
for k=1:numel(names)
    assert(isfield(p,names{k}) && isequal(double(p.(names{k})),0), ...
        'sma:candidate_yuan_reduced_material_step_1d:CrossMaterialMechanism', ...
        'Cu-Al-Mn reduced provider rejects active cross-material field %s.', ...
        names{k});
end
end

function value = canonical_case_name(case_id)
names = {'cualmn_annealed','cualmn_drawn130','cualmn_drawn80'};
value = names{case_id-1};
end
