function receipt = validate_unified_state_contract_1d(state,tolerance)
%SMA.VALIDATE_UNIFIED_STATE_CONTRACT_1D Validate, but never infer, v1 state.
%
% This boundary is deliberately separate from the legacy 15-value state.
% It validates an explicitly supplied state and does not translate, clamp,
% fill, or mutate any production history.

if nargin<2
    tolerance=1.0e-12;
end
assert(isstruct(state) && isscalar(state), ...
    'sma:unified_state_contract:StateType', ...
    'The unified state must be a scalar struct.');
assert(isscalar(tolerance) && isfinite(tolerance) && tolerance>0, ...
    'sma:unified_state_contract:Tolerance', ...
    'The contract tolerance must be a positive finite scalar.');

schema=require_text(state,'schema');
assert(strcmp(schema,'unified_state_1d_v1'), ...
    'sma:unified_state_contract:Schema', ...
    'Unsupported unified state schema %s.',schema);
identity=require_struct(state,'identity');
material_card_id=require_text(identity,'material_card_id');
model_variant_id=require_text(identity,'model_variant_id');
state_id=require_text(identity,'state_id');

phase=require_struct(state,'phase');
xi_A=require_scalar(phase,'xi_A');
xi_R=require_scalar(phase,'xi_R');
xi_M=require_scalar(phase,'xi_M');
phase_values=[xi_A,xi_R,xi_M];
assert(all(phase_values>=-tolerance) && all(phase_values<=1+tolerance), ...
    'sma:unified_state_contract:PhaseBounds', ...
    'Absolute A/R/M phase fractions must lie in [0,1].');
phase_sum=sum(phase_values);
assert(abs(phase_sum-1)<=tolerance, ...
    'sma:unified_state_contract:PhaseClosure', ...
    'Absolute A/R/M phase fractions must sum to one.');
relative_R=require_scalar(phase,'relative_R_within_AR');
relative_defined=require_logical(phase,'relative_R_defined');
ar_inventory=xi_A+xi_R;
if ar_inventory>tolerance
    assert(relative_defined, ...
        'sma:unified_state_contract:RelativeRDefinition', ...
        'relative_R_within_AR must be declared defined for nonzero A+R inventory.');
    relative_residual=relative_R-xi_R/ar_inventory;
    assert(relative_R>=-tolerance && relative_R<=1+tolerance && ...
        abs(relative_residual)<=tolerance, ...
        'sma:unified_state_contract:RelativeRClosure', ...
        'The relative R coordinate is inconsistent with absolute A/R fractions.');
else
    assert(~relative_defined && abs(relative_R)<=tolerance, ...
        'sma:unified_state_contract:RelativeRZeroInventory', ...
        'The relative R coordinate must be undefined and zero at zero A+R inventory.');
    relative_residual=0.0;
end

strain=require_struct(state,'strain');
component_names={'eps_elastic','eps_thermal','eps_R','eps_MT', ...
    'eps_TRIP','eps_ARP'};
components=zeros(1,numel(component_names));
for k=1:numel(component_names)
    components(k)=require_scalar(strain,component_names{k});
end
eps_total=require_scalar(strain,'eps_total');
strain_residual=sum(components)-eps_total;
strain_scale=max(1.0,abs(eps_total));
assert(abs(strain_residual)<=tolerance*strain_scale, ...
    'sma:unified_state_contract:StrainClosure', ...
    'The declared total strain does not equal the six named components.');

residual_M=require_struct(state,'residual_martensite');
residual_authority=require_text(residual_M,'authority');
residual_field=require_text(residual_M,'source_field_name');
xi_Mr=require_scalar(residual_M,'value');
assert(xi_Mr>=-tolerance && xi_Mr<=xi_M+tolerance, ...
    'sma:unified_state_contract:ResidualMBounds', ...
    'Residual martensite must lie between zero and current absolute M.');
switch residual_authority
    case 'none'
        assert(strcmp(residual_field,'none') && abs(xi_Mr)<=tolerance, ...
            'sma:unified_state_contract:ResidualMNone', ...
            'Authority none requires source_field_name=none and zero value.');
    case 'reduced_legacy_xi_res'
        assert(strcmp(residual_field,'xi_res'), ...
            'sma:unified_state_contract:ResidualMField', ...
            'Reduced residual-M authority must name xi_res.');
    case 'zhang_source_xi_Mr'
        assert(strcmp(residual_field,'zhang_xi_Mr'), ...
            'sma:unified_state_contract:ResidualMField', ...
            'Zhang source residual-M authority must name zhang_xi_Mr.');
    otherwise
        error('sma:unified_state_contract:ResidualMAuthority', ...
            'Unsupported residual-M authority %s.',residual_authority);
end

reversal=require_struct(state,'reversal_memory');
xi_M_anchor=require_scalar(reversal,'xi_M_forward_anchor');
eps_MT_anchor=require_scalar(reversal,'eps_MT_forward_anchor');
assert(xi_M_anchor>=xi_M-tolerance && xi_M_anchor<=1+tolerance, ...
    'sma:unified_state_contract:ReversalAnchor', ...
    'The forward M anchor must not be below the accepted M fraction.');

plastic=require_struct(state,'plastic_ledger');
plastic_representation=require_text(plastic,'representation');
lineage_reference=require_optional_text(plastic,'lineage_reference');
lossless_lineage=require_logical(plastic,'lossless_lineage');
switch plastic_representation
    case 'legacy_bulk'
        assert(~lossless_lineage && isempty(lineage_reference), ...
            'sma:unified_state_contract:LegacyPlasticLedger', ...
            'Legacy bulk plastic state must not claim a lossless cohort lineage.');
        cohort_path_ledger_eligible=false;
    case 'source_cohort'
        assert(lossless_lineage && ~isempty(lineage_reference), ...
            'sma:unified_state_contract:CohortPlasticLedger', ...
            'Source cohort state requires a nonempty lossless lineage reference.');
        cohort_path_ledger_eligible=true;
    otherwise
        error('sma:unified_state_contract:PlasticRepresentation', ...
            'Unsupported plastic representation %s.',plastic_representation);
end

receipt=struct( ...
    'status','PASS_UNIFIED_STATE_CONTRACT_V1', ...
    'schema',schema, ...
    'material_card_id',material_card_id, ...
    'model_variant_id',model_variant_id, ...
    'state_id',state_id, ...
    'phase_sum_residual',phase_sum-1.0, ...
    'relative_R_residual',relative_residual, ...
    'strain_closure_residual',strain_residual, ...
    'residual_M_authority',residual_authority, ...
    'plastic_representation',plastic_representation, ...
    'cohort_path_ledger_eligible',cohort_path_ledger_eligible, ...
    'xi_M_forward_anchor',xi_M_anchor, ...
    'eps_MT_forward_anchor',eps_MT_anchor, ...
    'state_modified',false, ...
    'production_forward_connected',false);
end

function child=require_struct(parent,name)
assert(isfield(parent,name) && isstruct(parent.(name)) && ...
    isscalar(parent.(name)), ...
    'sma:unified_state_contract:MissingStruct', ...
    'Missing scalar struct field %s.',name);
child=parent.(name);
end

function value=require_scalar(parent,name)
assert(isfield(parent,name) && isnumeric(parent.(name)) && ...
    isscalar(parent.(name)) && isreal(parent.(name)) && ...
    isfinite(parent.(name)), ...
    'sma:unified_state_contract:FiniteScalar', ...
    'Field %s must be a finite real scalar.',name);
value=double(parent.(name));
end

function value=require_logical(parent,name)
assert(isfield(parent,name) && islogical(parent.(name)) && ...
    isscalar(parent.(name)), ...
    'sma:unified_state_contract:LogicalScalar', ...
    'Field %s must be a scalar logical.',name);
value=parent.(name);
end

function value=require_text(parent,name)
assert(isfield(parent,name), ...
    'sma:unified_state_contract:MissingText', ...
    'Missing text field %s.',name);
raw=parent.(name);
assert((ischar(raw) && (isrow(raw) || isempty(raw))) || ...
    (isstring(raw) && isscalar(raw) && ~ismissing(raw)), ...
    'sma:unified_state_contract:TextScalar', ...
    'Field %s must be a text scalar.',name);
value=char(raw);
assert(~isempty(strtrim(value)), ...
    'sma:unified_state_contract:EmptyText', ...
    'Field %s must not be empty.',name);
end

function value=require_optional_text(parent,name)
assert(isfield(parent,name), ...
    'sma:unified_state_contract:MissingText', ...
    'Missing text field %s.',name);
raw=parent.(name);
assert((ischar(raw) && (isrow(raw) || isempty(raw))) || ...
    (isstring(raw) && isscalar(raw) && ~ismissing(raw)), ...
    'sma:unified_state_contract:TextScalar', ...
    'Field %s must be a text scalar.',name);
value=char(raw);
end
